export function setLanguage(value) { current = Object.hasOwn(messages, value) ? value : 'en'; return current; }
export function getLanguage() { return current; }
export function t(key, params = {}) { const value = messages[current][key] ?? messages.en[key] ?? key; return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? '')); }
export function translatePage(root = document) { document.documentElement.lang = current === 'zh' ? 'zh-CN' : current; for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n); for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder); for (const node of root.querySelectorAll('[data-i18n-aria]')) node.setAttribute('aria-label', t(node.dataset.i18nAria)); }
